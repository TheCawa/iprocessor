; Самый простой графический тест: два пикселя в режиме 320x200x256.
.org 0x00060000
.text

start:
    ; Переключаем видеокарту в графический режим 320x200.
    LDI.B XL1, 0x01
    STR.B XL1, [0x0002001A]

    LDI.DW A0, 0x00100000     ; база видеопамяти

    ; Первый пиксель — белый в точке (50, 100).
    LDI.DW A1, (100 * 320 + 50)
    ADD A1, A0
    LDI.B XL1, 0xFF           ; белый в VGA 256-цветной палитре
    STR.B XL1, [A1]

    ; Второй пиксель — красный в точке (200, 50).
    LDI.DW A1, (50 * 320 + 200)
    ADD A1, A0
    LDI.B XL1, 0xB4           ; ярко-красный (R=5, G=0, B=0)
    STR.B XL1, [A1]

    HALT
