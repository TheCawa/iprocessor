; Перемещение текстового курсора через прямую запись в видеопамять.
; Рисует буквы в четырёх углах экрана 80x25.
.org 0x00060000
.text

start:
    LDI.DW A0, 0x00100000     ; база текстового буфера
    LDI.B XL2, 0x0F           ; белый цвет на чёрном фоне

    ; Левый верхний угол (0,0) — 'A'.
    LDI.B XL1, 'A'
    STR.B XL1, [A0]
    STR.B XL2, [A0 + 1]

    ; Правый верхний угол (79,0).
    LDI.DW A1, (79 * 2)
    ADD A1, A0
    LDI.B XL1, 'B'
    STR.B XL1, [A1]
    STR.B XL2, [A1 + 1]

    ; Левый нижний угол (0,24).
    LDI.DW A1, (24 * 80 * 2)
    ADD A1, A0
    LDI.B XL1, 'C'
    STR.B XL1, [A1]
    STR.B XL2, [A1 + 1]

    ; Правый нижний угол (79,24).
    LDI.DW A1, ((24 * 80 + 79) * 2)
    ADD A1, A0
    LDI.B XL1, 'D'
    STR.B XL1, [A1]
    STR.B XL2, [A1 + 1]

    ; Центр экрана (40,12).
    LDI.DW A1, ((12 * 80 + 40) * 2)
    ADD A1, A0
    LDI.B XL1, '*'
    STR.B XL1, [A1]
    LDI.B XL2, 0x0A           ; ярко-зелёный
    STR.B XL2, [A1 + 1]

    HALT
